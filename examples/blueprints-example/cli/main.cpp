void PrintUsage()
{
    std::cout
        << "Visual Lox CLI\n\n"
        << "Usage:\n"
        << "  vlox [--disassemble] <script.vlox> [arguments...]\n"
        << "  vlox inspect-definitions\n"
        << "  vlox validate --json <script.vlox>\n\n"
        << "Options:\n"
        << "  --disassemble  Print generated bytecode before execution.\n"
        << "  -h, --help     Show this help.\n";
}

int InspectDefinitions()
{
    VM& vm = VM::getInstance();
    NodeRegistry registry;
    RegisterStandardLibrary(registry);
    registry.RegisterNatives(vm);

    struct DefinitionSummary
    {
        std::string id;
        uint32_t revision = 1;
        std::string fingerprint;
        std::string displayName;
    };
    std::vector<DefinitionSummary> definitions;
    definitions.reserve(registry.nativeDefinitions.size() + registry.compiledDefinitions.size());
    for (const NativeFunctionDef& native : registry.nativeDefinitions)
        if (native.functionDef)
            definitions.push_back({ native.functionDef->id, native.functionDef->revision, native.functionDef->compatibilityFingerprint, native.functionDef->name });
    for (const CompiledNodeDefPtr& compiled : registry.compiledDefinitions)
        if (compiled && compiled->functionDef)
            definitions.push_back({ compiled->id, compiled->revision, compiled->functionDef->compatibilityFingerprint, compiled->name });
    std::sort(definitions.begin(), definitions.end(), [](const DefinitionSummary& left, const DefinitionSummary& right) { return left.id < right.id; });

    std::cout << "definition_id\trevision\tfingerprint\tdisplay_name\n";
    for (const DefinitionSummary& definition : definitions)
        std::cout << definition.id << '\t' << definition.revision << '\t' << definition.fingerprint << '\t' << definition.displayName << '\n';
    return 0;
}

std::string EscapeJson(const std::string& value)
{
    std::string result;
    result.reserve(value.size() + 2);
    for (const unsigned char character : value)
    {
        switch (character)
        {
        case '"': result += "\\\""; break;
        case '\\': result += "\\\\"; break;
        case '\b': result += "\\b"; break;
        case '\f': result += "\\f"; break;
        case '\n': result += "\\n"; break;
        case '\r': result += "\\r"; break;
        case '\t': result += "\\t"; break;
        default:
            if (character < 0x20)
            {
                constexpr char hex[] = "0123456789abcdef";
                result += "\\u00";
                result += hex[character >> 4];
                result += hex[character & 0x0f];
            }
            else
            {
                result += static_cast<char>(character);
            }
            break;
        }
    }
    return result;
}

int ValidateDocumentJson(int argc, char** argv)
{
    if (argc != 4 || std::string(argv[2]) != "--json")
    {
        PrintUsage();
        return 2;
    }

    VM& vm = VM::getInstance();
    NodeRegistry registry;
    RegisterStandardLibrary(registry);
    registry.RegisterNatives(vm);
    Script script;
    IDGenerator ids;
    vm.setExternalMarkingFunc([&]()
    {
        MarkNodeRegistryRoots(registry, vm);
        ScriptUtils::MarkScriptRoots(script);
    });

    const SerializationResult loaded = ScriptSerializer::Load(argv[3], registry, script, ids);
    ScriptCompileResult compiled;
    if (loaded) compiled = ScriptRuntime::Compile(vm, script, {});
    const bool valid = loaded && static_cast<bool>(compiled);
    std::cout << "{\"valid\":" << (valid ? "true" : "false") << ",\"diagnostics\":[";
    bool first = true;
    const auto separator = [&]()
    {
        if (!first) std::cout << ',';
        first = false;
    };
    for (const SerializationDiagnostic& diagnostic : loaded.diagnostics)
    {
        separator();
        const char* severity = diagnostic.severity == SerializationDiagnosticSeverity::Error ? "error"
            : diagnostic.severity == SerializationDiagnosticSeverity::Warning ? "warning" : "info";
        std::cout << "{\"severity\":\"" << severity << "\",\"code\":\"" << EscapeJson(diagnostic.code) << "\",\"path\":\""
                  << EscapeJson(diagnostic.path) << "\",\"identity\":\"" << EscapeJson(diagnostic.identity) << "\",\"message\":\""
                  << EscapeJson(diagnostic.message) << "\"}";
    }
    for (const ValidationDiagnostic& diagnostic : compiled.validation.diagnostics)
    {
        separator();
        std::cout << "{\"severity\":\"" << (diagnostic.severity == DiagnosticSeverity::Error ? "error" : "warning") << "\",\"code\":\""
                  << EscapeJson(diagnostic.code) << "\",\"path\":\"" << EscapeJson(diagnostic.graphName) << "\",\"identity\":\"node:"
                  << diagnostic.nodeId.Get() << "\",\"message\":\"" << EscapeJson(diagnostic.message) << "\"}";
    }
    std::cout << "]}\n";
    return valid ? 0 : 3;
}

